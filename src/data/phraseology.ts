export function searchPhraseologisms(query: string): Phraseologism[] {
  if (!query.trim()) return PHRASEOLOGISMS;
  const q = query.toLowerCase().trim();
  return PHRASEOLOGISMS.filter((p) => {
    if (p.title.toLowerCase().includes(q)) return true;
    if (p.forms.some((f) => f.toLowerCase().includes(q))) return true;
    if (p.keywords.some((k) => k.toLowerCase().includes(q))) return true;
    if (p.meaning.toLowerCase().includes(q)) return true;
    return false;
  });
}

export function filterPhraseologisms(
  items: Phraseologism[],
  themes: ThemeTag[],
  styles: StyleTag[],
  situations: string[]
): Phraseologism[] {
  return items.filter((p) => {
    if (themes.length > 0 && !themes.some((t) => p.themes.includes(t))) return false;
    if (styles.length > 0 && !styles.includes(p.style)) return false;
    if (situations.length > 0 && !situations.some((s) => p.situations.includes(s))) return false;
    return true;
  });
}

export function getPhraseologismById(id: string): Phraseologism | undefined {
  return PHRASEOLOGISMS.find((p) => p.id === id);
}
